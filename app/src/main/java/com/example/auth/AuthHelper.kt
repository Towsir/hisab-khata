private const val TAG = "Auth"

private val BD_MOBILE_E164_REGEX = Regex("^\\+8801[3-9][0-9]{8}$")

/**
 * Safely unwraps a Compose or themed ContextWrapper to its host Activity so
 * Jetpack Credential Manager can display the Google Sign-In sheet reliably.
 */
tailrec fun Context.findActivity(): Activity? = when (this) {
    is Activity -> this
    is ContextWrapper -> baseContext.findActivity()
    else -> null
}

/**
 * Normalizes Bangladeshi mobile numbers into E.164 format (+8801XXXXXXXXX).
 * Accepts 01XXXXXXXXX, 1XXXXXXXXX, 8801XXXXXXXXX, +8801XXXXXXXXX, and common
 * double-zero prefix typos like +88001XXXXXXXXX.
 * Returns null if the number is not a valid Bangladeshi mobile number.
 */
fun normalizeBangladeshiPhone(rawInput: String): String? {
    val cleaned = rawInput.trim().replace(Regex("[\\s\\-()]"), "")
    if (cleaned.isEmpty()) return null

    val candidate = when {
        cleaned.startsWith("+88001") -> "+880" + cleaned.removePrefix("+8800")
        cleaned.startsWith("88001") -> "+880" + cleaned.removePrefix("8800")
        cleaned.startsWith("+880") -> cleaned
        cleaned.startsWith("880") -> "+$cleaned"
        cleaned.startsWith("01") -> "+88$cleaned"
        cleaned.startsWith("1") -> "+880$cleaned"
        else -> return null
    }
    return if (BD_MOBILE_E164_REGEX.matches(candidate)) candidate else null
}

/**
 * Formats a normalized E.164 Bangladeshi number (+8801712345678) into a readable string (+880 1712-345678).
 */
fun formatBangladeshiPhoneDisplay(phone: String): String {
    val normalized = normalizeBangladeshiPhone(phone) ?: return phone.trim()
    val localPart = normalized.removePrefix("+880") // 10 digits: 1712345678
    return "+880 ${localPart.substring(0, 4)}-${localPart.substring(4)}"
}

fun FirebaseAuth.authStateFlow(): Flow<FirebaseUser?> = callbackFlow {
    val listener = FirebaseAuth.AuthStateListener { auth ->
        trySend(auth.currentUser)
    }
    addAuthStateListener(listener)
    awaitClose { removeAuthStateListener(listener) }
}

fun attemptAutoSignIn(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onUnauthenticated: () -> Unit,
    scope: CoroutineScope
) {
    if (Firebase.auth.currentUser != null) {
        onAuthSuccess()
        return
    }
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (e: Exception) {
        onUnauthenticated()
        return
    }

    val googleIdOption = GetGoogleIdOption.Builder()
        .setFilterByAuthorizedAccounts(true)
        .setServerClientId(clientId)
        .setAutoSelectEnabled(true)
        .build()

    val request = GetCredentialRequest.Builder()
        .addCredentialOption(googleIdOption)
        .build()

    scope.launch {
        try {
            val activityContext = context.findActivity() ?: context
            val result = credentialManager.getCredential(activityContext, request)
            val credential = result.credential
            if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                Firebase.auth.signInWithCredential(authCredential).await()
                onAuthSuccess()
            } else {
                onUnauthenticated()
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            onUnauthenticated()
        }
    }
}

fun onGoogleSignInClicked(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onAuthError: (String) -> Unit,
    scope: CoroutineScope,
    onAuthCancelled: () -> Unit = {}
) {
    val clientId = try {
        context.getString(R.string.default_web_client_id)
    } catch (e: Exception) {
        onAuthError("Google Sign-In configuration is missing. Please reopen the app and try again.")
        return
    }

    val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
    val request = GetCredentialRequest.Builder()
        .addCredentialOption(signInOption)
        .build()

    scope.launch {
        try {
            val activityContext = context.findActivity() ?: context
            val result = credentialManager.getCredential(activityContext, request)
            val credential = result.credential
            if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val googleIdToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
                val authCredential = GoogleAuthProvider.getCredential(googleIdToken, null)
                Firebase.auth.signInWithCredential(authCredential).await()
                onAuthSuccess()
            } else {
                onAuthError("Unexpected credential type received. Please try signing in again.")
            }
        } catch (e: CancellationException) {
            throw e
        } catch (e: GetCredentialCancellationException) {
            Log.w(TAG, "Google Sign-In flow cancelled or dismissed: ${e.message}", e)
            onAuthCancelled()
        } catch (e: NoCredentialException) {
            Log.w(TAG, "No Google credentials available on device: ${e.message}", e)
            onAuthError("No Google account found on this device. Please add a Google account in device Settings and try again.")
        } catch (e: Exception) {
            Log.e(TAG, "Google Sign-In failed", e)
            onAuthError(e.localizedMessage ?: "Sign in failed. Please check your connection and try again.")
        }
    }
}

fun signOutUser(
    credentialManager: CredentialManager,
    scope: CoroutineScope,
    onSignOutComplete: () -> Unit = {}
) {
    scope.launch {
        withContext(NonCancellable) {
            try {
                credentialManager.clearCredentialState(ClearCredentialStateRequest())
            } catch (e: Exception) {
                Log.w(TAG, "Failed to clear credential state: ${e.message}")
            } finally {
                Firebase.auth.signOut()
                onSignOutComplete()
            }
        }
    }
}
